test('请求中修改偏好不会显示过期结果', async ({ page }) => {
  await page.route('**/api/recommend', async route => {
    await new Promise(resolve => setTimeout(resolve, 700))
    await route.fulfill({ json: { items: [], total_candidates: 0, message: '旧请求', metadata: {} } })
  })
  await submit(page)
  await expect(page.getByTestId('recommend-loading')).toBeVisible()
  await page.getByRole('textbox', { name: '推荐预算' }).fill('10')
  await page.waitForTimeout(900)
  await expect(page.getByText('偏好已变更', { exact: true })).toBeVisible()
  await expect(page.getByTestId('recommend-item')).toHaveCount(0)
  await expect(page.getByText('旧请求', { exact: true })).toHaveCount(0)
  await page.unroute('**/api/recommend')
  await submit(page); await expect(page.getByTestId('recommend-item')).toHaveCount(5)
})
test('Top4重复提交确定且无重复菜品', async ({ page }) => {
  await page.getByText('Top 4', { exact: true }).click(); await submit(page)
  await expect(page.getByTestId('recommend-item')).toHaveCount(4)
  const first = await ids(page)
  expect(new Set(first).size).toBe(4)
  await submit(page); await expect(page.getByTestId('recommend-item')).toHaveCount(4)
  expect(await ids(page)).toEqual(first)
})
test('截图条件微辣10元夜宵不推荐无关烤玉米', async ({ page }) => {
  await page.getByRole('textbox', { name: '推荐预算' }).fill('10')
  await select(page, '推荐口味', '微辣')
  await select(page, '推荐用餐时段', '夜宵')
  await submit(page)
  await expect(page.getByText('暂无符合条件的推荐', { exact: true })).toBeVisible()
  await expect(page.getByTestId('recommend-item')).toHaveCount(0)
  await expect(page.getByText('烤玉米', { exact: true })).toHaveCount(0)
  await expect(page.getByTestId('recommend-count')).toContainText('0 条推荐')
  const folder = process.env.CAMPUSBITE_EVIDENCE || '../docs/evidence/round04_taste_fix'
  await page.screenshot({ path: `${folder}/screenshots/mild_spicy_night_no_match.png`, fullPage: true })
  await page.getByRole('textbox', { name: '推荐预算' }).fill('30'); await submit(page)
  const response = await page.request.post('/api/recommend', { data: { budget: 30, tastes: ['微辣'], meal_period: '夜宵' } })
  const expected = (await response.json()).items
  expect(expected.length).toBeGreaterThan(0)
  await expect(page.getByTestId('recommend-item')).toHaveCount(expected.length)
  expect(await ids(page)).toEqual(expected.map(r => r.dish.id))
  expect(expected.every(r => r.dish.taste_tags.includes('微辣'))).toBeTruthy()
})
