test('推荐API失败可恢复且加载状态可见', async ({ page }) => {
  await page.route('**/api/recommend', async route => { await new Promise(r => setTimeout(r, 600)); await route.fulfill({ status: 503, json: { error: { message: '餐饮信息暂不可用，请稍后重试。' } } }) })
  await submit(page)
  await expect(page.getByTestId('recommend-loading')).toBeVisible()
  await expect(page.getByText('暂时无法推荐', { exact: true })).toBeVisible()
  await page.unroute('**/api/recommend')
  await page.getByRole('button', { name: '重新推荐' }).click()
  await expect(page.getByTestId('recommend-item')).toHaveCount(5)
})
