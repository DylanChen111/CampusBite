import { test, expect } from '@playwright/test'
const submit = page => page.getByRole('button', { name: '生成推荐', exact: true }).click()
async function select(page, label, option) {
  await page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: label, exact: true }) }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
  await page.getByRole('heading', { name: '智能推荐', exact: true }).click()
}
const ids = page => page.getByTestId('dish-card').evaluateAll(cards => cards.map(c => Number(c.getAttribute('href').split('/').pop())))
let consoleErrors, pageErrors
test.beforeEach(async ({ page }) => {
  consoleErrors = []; pageErrors = []
  page.on('pageerror', error => pageErrors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  await page.goto('/recommend')
  await expect(page.getByRole('button', { name: '生成推荐', exact: true })).toBeEnabled()
})
test.afterEach(async ({}, info) => {
  await info.attach('browser-console', { body: JSON.stringify({ consoleErrors, pageErrors }), contentType: 'application/json' })
  expect(pageErrors).toEqual([])
  expect(info.title.includes('API失败') ? consoleErrors.filter(s => !/^Failed to load resource:/.test(s)) : consoleErrors).toEqual([])
})
test('口味变化清除旧结果并更新实际排序', async ({ page }) => {
  await select(page, '推荐口味', '清淡'); await submit(page)
  await expect(page.getByTestId('recommend-item')).toHaveCount(5)
  const old = await ids(page)
  const control = page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '推荐口味' }) })
  await control.hover(); await control.locator('.el-select__clear').click()
  await expect(page.getByText('偏好已变更', { exact: true })).toBeVisible()
  await expect(page.getByTestId('recommend-item')).toHaveCount(0)
  await select(page, '推荐口味', '麻辣'); await submit(page)
  const expected = await page.request.post('/api/recommend', { data: { tastes: ['麻辣'] } })
  const matches = (await expected.json()).items
  await expect(page.getByTestId('recommend-item')).toHaveCount(matches.length)
  expect(await ids(page)).not.toEqual(old)
  expect(await ids(page)).toEqual(matches.map(r => r.dish.id))
})
test('预算距离营业忌口组合和Top3真正生效', async ({ page }) => {
  await page.getByRole('textbox', { name: '推荐预算' }).fill('20')
  await page.getByRole('textbox', { name: '推荐距离' }).fill('500')
  await select(page, '推荐忌口', '花生')
  await page.getByText('仅看模拟营业中', { exact: true }).click()
  await page.getByText('Top 3', { exact: true }).click()
  await submit(page)
  await expect(page.getByTestId('recommend-item')).toHaveCount(3)
  const response = await page.request.post('/api/recommend', { data: { budget: 20, max_distance_m: 500, avoid: ['花生'], only_open: true, top_k: 3 } })
  expect(await ids(page)).toEqual((await response.json()).items.map(r => r.dish.id))
})
